export function getNewslettersByCategory(categoryId) {
  return NEWSLETTERS.filter((n) => n.category === categoryId);
}

export function getDailyFeatured() {
  const dayOfYear = Math.floor(
    (Date.now() - new Date(new Date().getFullYear(), 0, 0)) / 86400000
  );
  return NEWSLETTERS[dayOfYear % NEWSLETTERS.length];
}
